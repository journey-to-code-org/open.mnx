import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { production } from '../../scripts/build-production.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');

test('dist/production is up to date with src', () => {
  execFileSync(process.execPath, [join(root, 'scripts/build-production.js'), '--check'], { stdio: 'pipe' });
});

test('the production build has the same exports, and no hot reloading', async () => {
  const [dev, prod] = await Promise.all([import('../../src/index.js'), import('../../dist/production/index.js')]);
  assert.deepEqual(Object.keys(prod).sort(), Object.keys(dev).sort());
  const element = readFileSync(join(root, 'dist/production/element.js'), 'utf8');
  for (const gone of ['__MNX_HOT__', '#reload', 'mnx.hot', '@hot']) assert.ok(!element.includes(gone), gone);
});

test('@hot fences', () => {
  assert.equal(production('a\n// @hot\nb\n// @hot-end\nc'), '// Generated by scripts/build-production.js from src/module: the runtime without hot reloading. Do not edit.\na\nc');
  assert.throws(() => production('a\n// @hot\nb'), /without @hot-end/);
  assert.throws(() => production('// @hot-end'), /without @hot/);
});
