import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { production } from '../../scripts/build-production.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');

test('dist/production is up to date with src', () => {
  execFileSync(process.execPath, [join(root, 'scripts/build-production.js'), '--check'], { stdio: 'pipe' });
});

test('the production build has the same exports, and no hot reloading or DevTools hook', async () => {
  const [dev, prod] = await Promise.all([import('../../src/index.js'), import('../../dist/production/index.js')]);
  assert.deepEqual(Object.keys(prod).sort(), Object.keys(dev).sort());
  for (const name of ['element.js', 'effect.js', 'deep.js']) {
    const code = readFileSync(join(root, 'dist/production', name), 'utf8');
    for (const gone of ['__ZUBRA_HOT__', '#reload', 'zubra.hot', '@hot', '@dev', 'devhook.js', 'devtools.js', '__ZUBRA_DEVTOOLS__']) {
      assert.ok(!code.includes(gone), `${name}: ${gone}`);
    }
  }
});

test('@hot and @dev fences', () => {
  const header = '// Generated by scripts/build-production.js from src/module: the runtime without hot reloading or the DevTools hook. Do not edit.\n';
  assert.equal(production('a\n// @hot\nb\n// @hot-end\nc'), `${header}a\nc`);
  assert.equal(production('a\n// @dev\nb\n// @dev-end\nc'), `${header}a\nc`);
  assert.throws(() => production('a\n// @hot\nb'), /without its end/);
  assert.throws(() => production('a\n// @dev\nb'), /without its end/);
  assert.throws(() => production('// @hot-end'), /@hot-end without its start/);
  assert.throws(() => production('// @dev-end'), /@dev-end without its start/);
});
