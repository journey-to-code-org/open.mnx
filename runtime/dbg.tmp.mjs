import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import { readFileSync, mkdtempSync, cpSync, writeFileSync } from 'node:fs';
import { join, extname } from 'node:path';
const repo = '/home/claude/open.mnx';
const site = mkdtempSync('/tmp/claude-0/dbg-');
cpSync(join(repo, 'runtime/src'), join(site, 'runtime'), { recursive: true });
const [fixture, ...args] = process.argv.slice(2);
writeFileSync(join(site, 'c.js'), execFileSync(join(repo, 'target/debug/mnx'), ['compile', fixture, '--emit', 'js']));
const html = execFileSync(join(repo, 'target/debug/mnx'), ['compile', fixture, ...args], { encoding: 'utf8' }).replace(/<!--[^]*?-->/g, '');
writeFileSync(join(site, 'index.html'), `<!doctype html><script type="importmap">{ "imports": { "@mnx/runtime": "/runtime/index.js" } }</script><body>${html}</body><script type="module">globalThis.__MNX_DEBUG__ = true; await import('/c.js'); window.ready = true;</script>`);
const server = createServer((req, res) => { const p = join(site, req.url === '/' ? 'index.html' : req.url); try { const b = readFileSync(p); res.writeHead(200, { 'content-type': { '.js': 'text/javascript', '.html': 'text/html' }[extname(p)] }).end(b); } catch { res.writeHead(404).end(); } });
await new Promise((r) => server.listen(0, r));
const browser = await chromium.launch(); const page = await browser.newPage();
page.on('console', (m) => console.log('console:', m.text()));
await page.goto(`http://localhost:${server.address().port}/`); await page.waitForFunction(() => window.ready);
await page.waitForTimeout(200);
console.log(await page.evaluate(() => document.body.innerHTML.slice(0, 900)));
await browser.close(); server.close();
