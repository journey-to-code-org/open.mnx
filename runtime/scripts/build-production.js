// The production build of the runtime (`dist/production/`, the `production` export condition):
// the same modules, without what only development uses, and minified. Code between `// @hot` and
// `// @hot-end` (hot reloading) or `// @dev` and `// @dev-end` (the DevTools hook) is left out,
// `globalThis.__ZUBRA_HOT__` reads as false, and each file is minified on its own (esbuild, pinned
// in devDependencies, so the output is the same everywhere): still one module per file, imported as
// before, but without comments and long names. `src/` is the runtime to read; this is the one a
// server without a bundler sends (`@zubra/server` in production), where it halves the bytes.
// `--check` fails if the build is out of date.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { transformSync } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'src');
const to = join(root, 'dist/production');
const check = process.argv.includes('--check');
// Modules only development imports (from `// @dev` blocks): not in the production build at all.
const DEV_ONLY = ['devhook.js', 'devtools.js'];

export function production(source, file = 'module') {
  const lines = source.split('\n');
  const out = [];
  let depth = 0;
  for (const [index, line] of lines.entries()) {
    const marker = line.trim();
    if (marker.startsWith('// @hot-end') || marker.startsWith('// @dev-end')) {
      if (!depth--) throw new Error(`${file}:${index + 1}: ${marker.slice(3, 11)} without its start`);
      continue;
    }
    if (marker.startsWith('// @hot') || marker.startsWith('// @dev')) {
      depth++;
      continue;
    }
    if (!depth) out.push(line);
  }
  if (depth) throw new Error(`${file}: @hot or @dev without its end`);
  const code = out.join('\n').replaceAll('globalThis.__ZUBRA_HOT__', 'false');
  return `// Generated by scripts/build-production.js from src/${file}: the runtime without hot reloading or the DevTools hook. Do not edit.\n${code}`;
}

/** `production()`'s module, minified, under the same header (a pointer back to its source). */
export function minified(source, file = 'module') {
  const stripped = production(source, file);
  const header = stripped.slice(0, stripped.indexOf('\n') + 1);
  const { code } = transformSync(stripped.slice(header.length), {
    minify: true,
    format: 'esm',
    target: 'esnext', // minify only: no syntax rewritten
    legalComments: 'none',
    sourcefile: `src/${file}`,
  });
  return `${header.replace('Do not edit.', 'Minified; read src/ instead. Do not edit.')}${code}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const stale = [];
  const files = readdirSync(from).filter((name) => name.endsWith('.js') && !DEV_ONLY.includes(name));
  if (!check) {
    rmSync(to, { recursive: true, force: true });
    mkdirSync(to, { recursive: true });
  }
  for (const name of files) {
    const built = minified(readFileSync(join(from, name), 'utf8'), name);
    const target = join(to, name);
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== built) stale.push(name);
    } else writeFileSync(target, built);
  }
  if (check) {
    const extra = existsSync(to) ? readdirSync(to).filter((name) => !files.includes(name)) : [];
    if (stale.length || extra.length) {
      console.error(`dist/production is out of date (${[...stale, ...extra].join(', ')}): run npm run build:production in runtime/`);
      process.exit(1);
    }
  }
}
