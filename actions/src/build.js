// `zubra-actions build`: a components folder's server functions as plain modules, for hosts that
// can't compile at start-up (a Cloudflare Worker has no disk and can't import code it generates).
// Your bundler (Wrangler, esbuild, Vite) then bundles them like any other import:
//
//   npx zubra-actions build components --out src/actions     # writes src/actions/index.js
//   import { actions } from './actions/index.js';
//   import { createActions } from '@zubra/actions/edge';
//   const forms = createActions({ actions });
//
// Rebuild when a component's server functions change; the files say they're generated.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { flatName, rewriteImports, serverHalves } from './compile.js';

const HEADER = '// Generated by `zubra-actions build` from';

/**
 * Writes `<out>/<component>.server.js` for each component with server functions, and
 * `<out>/index.js` exporting `actions`: every route. Resolves to the routes. Files it wrote before
 * that no longer have a component are removed; nothing else in `out` is touched.
 */
export async function buildActions({ components = 'components', out }) {
  if (!out) throw new TypeError('buildActions({ components, out }): `out` is the folder to write');
  const root = resolve(components);
  const dir = resolve(out);
  mkdirSync(dir, { recursive: true });
  const halves = await serverHalves(root);
  const written = new Set(['index.js']);
  // The same check the Node entry makes: two components may not define one URL.
  const urls = [];
  for (const { output } of halves) {
    for (const url of urlsOf(output)) {
      if (urls.includes(url)) throw new Error(`@zubra/actions: two components define ${url}`);
      urls.push(url);
    }
  }
  const imports = [];
  const maps = [];
  for (const [n, { path, output }] of halves.entries()) {
    const file = `${flatName(relative(root, path))}.server.js`;
    const source = relative(dir, path).split(sep).join('/');
    // Relative imports still reach the component's neighbours, from where the file now is.
    const code = rewriteImports(output, (specifier) => {
      const target = relative(dir, resolve(dirname(path), specifier)).split(sep).join('/');
      return target.startsWith('.') ? target : `./${target}`;
    });
    writeFileSync(join(dir, file), `${HEADER} ${source}. Don't edit it.\n${code}`);
    written.add(file);
    imports.push(`import { actions as a${n} } from './${file}';`);
    maps.push(`a${n}`);
  }
  writeFileSync(
    join(dir, 'index.js'),
    `${HEADER} ${relative(dir, root).split(sep).join('/') || '.'}. Don't edit it.\n` +
      `// Every component's 'use server' functions: { '/_zb/action/<tag>/<name>': fn }.\n` +
      `${imports.join('\n')}${imports.length ? '\n' : ''}\nexport const actions = { ${maps.map((m) => `...${m}`).join(', ')} };\n`,
  );
  // Leftovers from components that are gone (only files this command writes).
  for (const entry of readdirSync(dir)) {
    if (entry.endsWith('.server.js') && !written.has(entry)) rmSync(join(dir, entry));
  }
  return urls;
}

/** The URLs a server half's `actions` map names, read from the compiler's output (not run: it may import what only the host has). */
function urlsOf(output) {
  const map = /export const actions = \{([^]*?)\};/.exec(output)?.[1] ?? '';
  return [...map.matchAll(/"(\/_zb\/action\/[^"]+)"\s*:/g)].map(([, url]) => url);
}
