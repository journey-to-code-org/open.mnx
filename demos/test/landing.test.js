// The landing page in the built gallery (site/, Eleventy), read as a file with no browser. The page
// shows code it didn't type: the component is compiled when the page is built, and the by-hand
// version is read out of the README, so these check that what's shown is that, and the claims
// about it (line counts) are true.
//
//   node demos/build.mjs --out _site --base /zubra/ && node --test "demos/test/landing.test.js"
//
// GALLERY (default _site) says where the build is.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '../..');
const dir = resolve(repo, process.env.GALLERY ?? '_site');
const text = (html) => html.replace(/<[^>]+>/g, '').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');

const page = () => {
  assert.ok(existsSync(join(dir, 'index.html')), `no landing page in ${dir}: run node demos/build.mjs --out ${dir}`);
  return readFileSync(join(dir, 'index.html'), 'utf8');
};

test('the page shows the compiler\'s output for the sample, not typed text', () => {
  const shown = text(page());
  assert.ok(shown.includes('<copy-button text="npm create zubra">'), 'the compiled HTML, with the prop the page gave it');
  assert.ok(shown.includes('import { $define'), 'the compiled module');
  assert.ok(shown.includes('Generated by zubra from copy-button.zb'), 'the module header');
  assert.match(shown, /export (interface|declare|class|default|const|type)/, 'the typings');
});

test('the by-hand version is the README\'s, and the line counts shown are true', () => {
  const html = page();
  const readme = readFileSync(join(repo, 'README.md'), 'utf8');
  const block = readme.match(/<summary>The same element written by hand[^<]*<\/summary>\s*```js\n([\s\S]*?)\n```/)[1];
  const source = readFileSync(join(repo, 'site/src/samples/copy-button.zb'), 'utf8').trim();
  assert.ok(text(html).includes(block.split('\n')[0]), 'the README\'s first line is on the page');
  assert.match(html, new RegExp(`<strong>${block.split('\n').length}</strong> lines by hand`));
  assert.match(html, new RegExp(`<strong>${source.split('\n').length}</strong> lines with Zubra`));
});

test('the pitch and the docs agree on the by-hand length', () => {
  // The README and the "Read the output" chapter say "about N lines"; N is within a few of the truth.
  const readme = readFileSync(join(repo, 'README.md'), 'utf8');
  const actual = readme.match(/<summary>The same element written by hand[^<]*<\/summary>\s*```js\n([\s\S]*?)\n```/)[1].split('\n').length;
  for (const file of ['README.md', 'docs/guide/08-read-the-output.md']) {
    const said = Number(readFileSync(join(repo, file), 'utf8').match(/about (\d+) lines/)?.[1]);
    assert.ok(Math.abs(said - actual) <= 5, `${file} says about ${said} lines; the hand-written version is ${actual}`);
  }
});

test('the page links the docs and the playground it ships beside', () => {
  const html = page();
  for (const path of ['docs/', 'playground/']) assert.ok(html.includes(`href="${process.env.GALLERY_BASE ?? '/zubra/'}${path}`), `a link to ${path}`);
});
